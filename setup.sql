create table if not exists public.aportes (
  id bigint generated by default as identity primary key,
  image_path text not null,
  image_url text not null,
  created_at timestamptz not null default now(),
  published boolean not null default true
);

alter table public.aportes enable row level security;

grant select, insert on public.aportes to anon;
grant usage, select on sequence public.aportes_id_seq to anon;

drop policy if exists "Lectura pública de aportes publicados" on public.aportes;
create policy "Lectura pública de aportes publicados"
on public.aportes for select to anon
using (published = true);

drop policy if exists "Visitantes pueden registrar aportes" on public.aportes;
create policy "Visitantes pueden registrar aportes"
on public.aportes for insert to anon
with check (
  published = true
  and length(image_path) between 1 and 180
  and image_url like 'https://%'
);

-- El bucket debe crearse desde Storage con:
-- nombre: paisaje-fotos
-- público: sí (las imágenes de la obra serán visibles para cualquier persona)
-- límite de archivo: 5 MB
-- tipos permitidos: image/jpeg, image/png, image/webp

drop policy if exists "Lectura pública de fotografías de la obra" on storage.objects;
create policy "Lectura pública de fotografías de la obra"
on storage.objects for select to anon
using (bucket_id = 'paisaje-fotos');

drop policy if exists "Visitantes pueden subir fotografías de la obra" on storage.objects;
create policy "Visitantes pueden subir fotografías de la obra"
on storage.objects for insert to anon
with check (
  bucket_id = 'paisaje-fotos'
  and lower(storage.extension(name)) in ('jpg', 'jpeg', 'png', 'webp')
);
